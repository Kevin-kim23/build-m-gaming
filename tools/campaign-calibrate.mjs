import fs from 'node:fs';
import {STAGES} from '../src/battle.js';
import {referenceArmy,simulateBattle} from './campaign-sim.mjs';
// Offline calibration only. Writes a fixed catalog; never adapts to the live player's army.
const rows=[];
for(const stage of STAGES){
 const s=referenceArmy(stage);let low=1,high=stage.hqPower*30,best=null;
 for(let i=0;i<28;i++){
  const hqPower=Math.max(1,Math.round((low+high)/2)),b=simulateBattle(s,stage.id,{hqPower}),seconds=b.elapsedMs/1000;
  if(b.status==='victory'&&(!best||Math.abs(seconds-100)<Math.abs(best.seconds-100)))best={id:stage.id,hqPower,seconds};
  if(b.status==='victory'&&seconds<100)low=hqPower+1;else high=hqPower-1;
 }
 if(!best||best.seconds<60||best.seconds>120)throw Error('Stage calibration failed: '+stage.id);
 rows.push(best);
}
fs.writeFileSync(new URL('../src/campaign-hq.js',import.meta.url),'// Fixed region siege HP. Generated by tools/campaign-calibrate.mjs; never scales with the player.\nexport const CAMPAIGN_HQ=Object.freeze('+JSON.stringify(rows.map(r=>r.hqPower))+');\n');
console.log('Calibrated '+rows.length+' regions. Run the full campaign report and tests before committing.');
